function seedCurrency(
  baseCurrency: SeededMonthlyAverageRate["baseCurrency"],
  monthlyRates: Record<string, number>,
  publishedUnit = 1,
): SeededMonthlyAverageRate[] {
  return Object.entries(monthlyRates).map(([yearMonth, averageRate]) => ({
    baseCurrency,
    quoteCurrency: "ILS",
    yearMonth: `${yearMonth}-01` as SeededMonthlyAverageRate["yearMonth"],
    averageRate: Number((averageRate / publishedUnit).toFixed(8)),
  }));
}
